"""Org LLM settings — the read/write side of the gateway config (Vol 4 §6.13,
TITAN-FRT-036). Private to the `llm` package; `router.py` is the only importer.

**What "switching the provider without a redeploy" actually rests on.** The
gateway resolves a fresh :class:`ModelRouter` from ``ConfigLoader.get()`` per
request, and that loader re-reads on mtime change. So persisting a routing
change as a file the loader already watches is enough — no restart, no DB read
on the hot path, and the worker process converges on its own next call. This
module writes ``config/models.overrides.yaml`` (see
:func:`titan.llm.config.overlay_path_for`) and never touches the hand-written
``models.yaml``, so an operator's comments and defaults survive and reverting is
`rm` of one file.

**Keys are never returned.** ``providers.*.api_key`` in the YAML is a
``${ENV_VAR}`` reference expanded at load time, so the loaded config holds real
secret material. :class:`ProviderOut` therefore reports only whether a key
resolved to something non-empty, plus its last four characters — enough to tell
"the key I pasted" from "some other key", and useless to an attacker. There is
no endpoint that echoes a key back.
"""

import os
import tempfile
import time
from decimal import Decimal
from pathlib import Path
from typing import Any

import structlog
import yaml
from pydantic import BaseModel, ConfigDict, Field

from titan.llm.config import ConfigLoader, GatewayConfig
from titan.llm.errors import UnknownAliasError
from titan.llm.gateway import LlmGateway
from titan.llm.models import ChatRequest, Message
from titan.llm.routing import ModelRouter

logger = structlog.get_logger("titan.llm.settings")

#: Header written at the top of every generated overlay, so an operator who
#: finds the file knows what wrote it and what to do about it.
_OVERLAY_HEADER = """\
# PROJECT TITAN — gateway overrides, GENERATED by Settings → LLM Providers.
#
# This file is merged over config/models.yaml on every gateway read (mtime hot
# reload), so a change here takes effect on the next request with no restart.
# Edit models.yaml for durable defaults; delete this file to revert to them.
"""


class ProviderOut(BaseModel):
    """One configured provider. Never carries key material."""

    name: str
    base_url: str | None = None
    #: True when the provider's api_key resolved to a non-empty value.
    key_configured: bool
    #: Last four characters of the resolved key, for recognition only.
    key_hint: str | None = None
    #: True when this provider needs no key at all (a local base_url provider
    #: such as Ollama), so the UI can show "ready" rather than "key missing".
    key_required: bool


class ModelAliasOut(BaseModel):
    model_config = ConfigDict(protected_namespaces=())

    alias: str
    provider: str
    model: str
    context_window: int | None = None
    input_per_mtok: Decimal | None = None
    output_per_mtok: Decimal | None = None


class BudgetsOut(BaseModel):
    """§8.4 caps. Named per_project_usd but enforced as ONE cap applied to
    whatever project a call carries — there is no per-project override table,
    so this is a single global ceiling and the UI says so."""

    per_project_usd: Decimal | None = None
    per_task_usd: Decimal | None = None
    action_on_exceeded: str | None = None


class LlmSettingsOut(BaseModel):
    default_alias: str
    #: The active model-policy PROFILE, which is what actually re-points agent
    #: turns. See :func:`effective_profile` — an agent never falls through to
    #: ``routing.default``, so this, not the default alias, is the switch that
    #: TITAN-FRT-036's "the next agent action logs the new provider" depends on.
    agent_profile: str | None = None
    embeddings_default_alias: str | None = None
    #: alias → ordered fallback chain.
    fallbacks: dict[str, list[str]] = Field(default_factory=dict)
    #: agent id → alias. §6.13's "per-agent-role model overrides".
    by_agent: dict[str, str] = Field(default_factory=dict)
    providers: list[ProviderOut] = Field(default_factory=list)
    aliases: list[ModelAliasOut] = Field(default_factory=list)
    budgets: BudgetsOut = Field(default_factory=BudgetsOut)
    #: True when an overrides file exists — i.e. some of the above came from
    #: Settings rather than from the operator's models.yaml.
    overridden: bool = False


class LlmSettingsUpdate(BaseModel):
    """Every field optional: a PATCH-shaped PUT. Only what is supplied is
    written to the overlay, so the UI can change the default provider without
    having to restate budgets it never showed."""

    model_config = ConfigDict(extra="forbid")

    default_alias: str | None = None
    #: Model-policy profile name, or "" to clear it back to the tier defaults.
    #: This is the field that re-points AGENT traffic; `default_alias` only
    #: moves callers that pass no alias of their own.
    agent_profile: str | None = None
    embeddings_default_alias: str | None = None
    fallbacks: dict[str, list[str]] | None = None
    by_agent: dict[str, str] | None = None
    per_project_usd: Decimal | None = Field(default=None, ge=0)
    per_task_usd: Decimal | None = Field(default=None, ge=0)
    action_on_exceeded: str | None = None


class ProviderTestResult(BaseModel):
    """A real round-trip, not a config lookup."""

    alias: str
    provider: str
    #: The alias's configured model.
    model: str
    ok: bool
    latency_ms: int
    detail: str = ""
    #: What actually SERVED the call. Differs from ``model`` when the gateway
    #: fell back, which is exactly the case a "Test" button must surface rather
    #: than report a cheerful green tick for a provider that is down.
    served_provider: str | None = None
    served_model: str | None = None
    #: Every alias this provider offers — §6.13's "reports latency/model list".
    #: Taken from the effective config, so it reflects any override just saved.
    provider_models: list[str] = Field(default_factory=list)


#: A hint is only shown when the key is long enough that four characters cannot
#: reconstruct it. A four-character key would otherwise be published whole.
_MIN_KEY_LENGTH_FOR_HINT = 12


def _key_hint(api_key: str | None) -> tuple[bool, str | None]:
    if not api_key:
        return False, None
    hint = api_key[-4:] if len(api_key) >= _MIN_KEY_LENGTH_FOR_HINT else None
    return True, hint


def describe(
    config: GatewayConfig, *, overridden: bool, agent_profile: str | None = None
) -> LlmSettingsOut:
    providers: list[ProviderOut] = []
    for name, spec in sorted(config.providers.items()):
        configured, hint = _key_hint(spec.api_key)
        # A provider reached over an explicit base_url with no key field at all
        # is a local runtime (Ollama). Distinguishing this is the difference
        # between "not configured yet" and "nothing to configure", which the
        # resolved config alone cannot express: a missing ${ENV_VAR} and a
        # deliberately keyless provider both arrive as the empty string.
        key_required = spec.api_key is not None
        providers.append(
            ProviderOut(
                name=name,
                base_url=spec.base_url,
                key_configured=configured,
                key_hint=hint,
                key_required=key_required,
            )
        )
    aliases = [
        ModelAliasOut(
            alias=name,
            provider=spec.provider,
            model=spec.model,
            context_window=spec.context_window,
            input_per_mtok=spec.price.input_per_mtok if spec.price else None,
            output_per_mtok=spec.price.output_per_mtok if spec.price else None,
        )
        for name, spec in sorted(config.model_aliases.items())
    ]
    budgets = config.budgets
    return LlmSettingsOut(
        default_alias=config.routing.default,
        agent_profile=agent_profile,
        embeddings_default_alias=config.routing.embeddings_default,
        fallbacks={k: list(v) for k, v in config.routing.fallbacks.items()},
        by_agent=dict(config.routing.by_agent),
        providers=providers,
        aliases=aliases,
        budgets=BudgetsOut(
            per_project_usd=budgets.per_project_usd if budgets else None,
            per_task_usd=budgets.per_task_usd if budgets else None,
            action_on_exceeded=budgets.action_on_exceeded if budgets else None,
        ),
        overridden=overridden,
    )


#: Overlay key holding the model-policy profile. It lives in the gateway
#: overlay rather than in a second file because it is the same operator
#: decision ("which provider serves work") and must be picked up by the same
#: mtime read — `config/model-policy.yaml` itself is behind an
#: ``@lru_cache(maxsize=4)`` keyed on its path, so a change THERE would not be
#: seen without a restart. The profile is a plain string, so reading it here
#: needs none of that cache.
_PROFILE_KEY = "agent_profile"


def effective_profile(loader: ConfigLoader, default: str | None) -> str | None:
    """The model-policy profile agent turns should resolve under.

    Settings' value wins over the process setting when one has been written.
    An empty string means "explicitly cleared" and resolves to None — which is
    distinct from "never set", where the process default still applies.
    """
    stored = read_overlay(loader.overlay_path).get(_PROFILE_KEY)
    if stored is None:
        return default
    text = str(stored).strip()
    return text or None


def read_overlay(path: Path) -> dict[str, Any]:
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError:
        return {}
    loaded = yaml.safe_load(raw)
    return dict(loaded) if isinstance(loaded, dict) else {}


def build_overlay(current: dict[str, Any], patch: LlmSettingsUpdate) -> dict[str, Any]:
    """Fold a partial update into the existing overlay document."""
    overlay = {k: dict(v) if isinstance(v, dict) else v for k, v in current.items()}
    routing = dict(overlay.get("routing") or {})
    budgets = dict(overlay.get("budgets") or {})

    if patch.agent_profile is not None:
        # Stored at the TOP level, not under `routing`: it is not part of
        # models.yaml's schema (GatewayConfig forbids extra keys), so it is
        # stripped before the merge — see `_read_merged`'s caller below.
        overlay[_PROFILE_KEY] = patch.agent_profile.strip()
    if patch.default_alias is not None:
        routing["default"] = patch.default_alias
    if patch.embeddings_default_alias is not None:
        routing["embeddings_default"] = patch.embeddings_default_alias
    if patch.fallbacks is not None:
        routing["fallbacks"] = {k: list(v) for k, v in patch.fallbacks.items()}
    if patch.by_agent is not None:
        routing["by_agent"] = dict(patch.by_agent)
    if patch.per_project_usd is not None:
        budgets["per_project_usd"] = float(patch.per_project_usd)
    if patch.per_task_usd is not None:
        budgets["per_task_usd"] = float(patch.per_task_usd)
    if patch.action_on_exceeded is not None:
        budgets["action_on_exceeded"] = patch.action_on_exceeded

    if routing:
        overlay["routing"] = routing
    if budgets:
        overlay["budgets"] = budgets
    return overlay


def write_overlay(path: Path, overlay: dict[str, Any]) -> None:
    """Write the overlay atomically.

    Temp file in the same directory then ``os.replace``, because the gateway is
    concurrently reading this exact path: a partially-written YAML document
    would be a parse error, and while the loader survives that by serving its
    last-good config, other processes starting up in that window would not.
    ``os.replace`` is atomic on both POSIX and Windows, so a reader sees either
    the old file or the new one and never a half-written one.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    body = _OVERLAY_HEADER + yaml.safe_dump(overlay, sort_keys=True, default_flow_style=False)
    fd, tmp_name = tempfile.mkstemp(dir=str(path.parent), prefix=path.name, suffix=".tmp")
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(body)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def apply_update(loader: ConfigLoader, patch: LlmSettingsUpdate) -> LlmSettingsOut:
    """Persist an update and return the resulting EFFECTIVE settings.

    Raises :class:`ValueError` when the merged result would be invalid — for
    example a ``default_alias`` no alias defines. The check is the loader's own
    validation of the merged document, so the API cannot accept a config the
    gateway would then reject: on failure the previous overlay is restored.
    """
    overlay_path = loader.overlay_path
    try:
        current = read_overlay(overlay_path)
    except (OSError, ValueError, yaml.YAMLError) as exc:
        # A hand-edited overlay with a syntax error must not 500 every save —
        # and the UI tells operators to hand-edit exactly this file.
        raise ValueError(f"{overlay_path.name} could not be read: {exc}") from exc

    overlay = build_overlay(current, patch)

    # Validate on a THROWAWAY loader, before the live one is touched at all.
    # Writing first and invalidating the shared loader would drop its last-good
    # config, so a base `models.yaml` that is itself broken (or a merge that
    # fails validation) would leave every LLM call 500-ing until someone fixed
    # the file — the exact outage the loader's last-good fallback exists to
    # prevent. Failing here leaves the live loader, and its cache, untouched.
    with tempfile.TemporaryDirectory() as scratch:
        probe_overlay = Path(scratch) / overlay_path.name
        write_overlay(probe_overlay, overlay)
        try:
            ConfigLoader(loader.path, probe_overlay).get()
        except (ValueError, OSError, yaml.YAMLError) as exc:
            raise ValueError(str(exc)) from exc

    write_overlay(overlay_path, overlay)
    loader.invalidate()
    config = loader.get()
    logger.info(
        "llm_settings.updated",
        overlay=str(overlay_path),
        default_alias=config.routing.default,
    )
    return describe(
        config,
        overridden=overrides_exist(loader),
        agent_profile=effective_profile(loader, None),
    )


def overrides_exist(loader: ConfigLoader) -> bool:
    return loader.overlay_path.is_file()


def clear_overrides(loader: ConfigLoader) -> LlmSettingsOut:
    """Delete the overlay — "revert to the operator's models.yaml"."""
    loader.overlay_path.unlink(missing_ok=True)
    loader.invalidate()
    return describe(
        loader.get(),
        overridden=overrides_exist(loader),
        agent_profile=effective_profile(loader, None),
    )


#: The probe sent by "Test". Deliberately the smallest useful completion: one
#: short user turn and a hard cap of a few tokens, so the check costs a
#: fraction of a cent and cannot be turned into a free generation endpoint.
_PROBE_PROMPT = "Reply with the single word: ok"
_PROBE_MAX_TOKENS = 16


async def test_alias(loader: ConfigLoader, gateway: LlmGateway, alias: str) -> ProviderTestResult:
    """Send a real minimal completion through the gateway and time it.

    §6.13's "Test performs a live round-trip and reports latency/model list".
    The latency is the wall clock of an ACTUAL provider call: a config-only
    check would report a provider reachable when its key is wrong, which is
    precisely the case this button exists to catch.

    It goes through ``gateway.chat`` rather than an adapter directly, so the
    probe is subject to the same budget holds, retries and ledger writes as
    real traffic — a test call is real spend and is recorded as such.
    """
    config = loader.get()
    try:
        resolved = ModelRouter(config).resolve(alias)
    except UnknownAliasError as exc:
        raise ValueError(f"unknown model alias '{alias}'") from exc

    siblings = sorted(
        name for name, spec in config.model_aliases.items() if spec.provider == resolved.provider
    )
    request = ChatRequest(
        model_alias=alias,
        messages=[Message(role="user", content=_PROBE_PROMPT)],
        max_tokens=_PROBE_MAX_TOKENS,
        temperature=0.0,
    )

    started = time.monotonic()
    try:
        response = await gateway.chat(request)
    except Exception as exc:  # noqa: BLE001 — every failure is a reportable RESULT
        # A failed provider test is a 200 with ok=false, not a 5xx: "your key is
        # wrong" is the answer to the question the button asked, and surfacing
        # it as a server error would make the UI show a generic failure toast
        # instead of the provider's own message.
        elapsed = int((time.monotonic() - started) * 1000)
        logger.info("llm_settings.test_failed", alias=alias, error=str(exc))
        return ProviderTestResult(
            alias=alias,
            provider=resolved.provider,
            model=resolved.model_id,
            ok=False,
            latency_ms=elapsed,
            detail=str(exc)[:500],
            provider_models=siblings,
        )
    elapsed = int((time.monotonic() - started) * 1000)
    degraded = response.provider != resolved.provider or response.model_id != resolved.model_id
    return ProviderTestResult(
        alias=alias,
        provider=resolved.provider,
        model=resolved.model_id,
        ok=not degraded,
        latency_ms=elapsed,
        detail=(
            f"served by fallback {response.provider}/{response.model_id}"
            if degraded
            else "round-trip succeeded"
        ),
        served_provider=response.provider,
        served_model=response.model_id,
        provider_models=siblings,
    )


