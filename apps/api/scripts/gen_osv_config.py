"""Render `security/scan-exceptions.yaml` into an osv-scanner config (SEC-100/104).

`scan-exceptions.yaml` is documented as the ONLY sanctioned way to ship past a
blocking finding, but nothing consumed it: `check-exceptions` validated the
registry while `osv-scan` ran with no config, so an entry there had no effect on
the gate it was supposed to govern.

This closes that loop. `make osv-scan` regenerates `osv-scanner.toml` from the
registry immediately before scanning, so the two can never drift: an exception
takes effect only while it is in the registry, and the registry's `expires` date
becomes the scanner's `ignoreUntil`. An expired entry fails `check-exceptions`
AND stops suppressing its finding, which is the intended behaviour — there is no
permanent suppression.

The generated file is build output, not source: it is gitignored and rewritten
on every run. Only `tool: osv-scanner` entries are rendered; the other tools in
the registry have their own gates.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[3]
EXCEPTIONS_PATH = REPO_ROOT / "security" / "scan-exceptions.yaml"
OUTPUT_PATH = REPO_ROOT / "osv-scanner.toml"
TOOL = "osv-scanner"


def _as_date(value: Any) -> date | None:
    if isinstance(value, date):
        return value
    try:
        return date.fromisoformat(str(value))
    except ValueError:
        return None


def render(doc: dict[str, Any]) -> str:
    entries = doc.get("exceptions") or []
    lines = [
        "# GENERATED by apps/api/scripts/gen_osv_config.py — DO NOT EDIT.",
        "# Source of truth: security/scan-exceptions.yaml (TITAN-SEC-100).",
        "",
    ]
    count = 0
    for entry in entries:
        if not isinstance(entry, dict) or entry.get("tool") != TOOL:
            continue
        vuln_id = str(entry.get("id", "")).strip()
        expires = _as_date(entry.get("expires"))
        if not vuln_id or expires is None:
            continue  # malformed — check_scan_exceptions.py reports it
        reason = " ".join(str(entry.get("reason", "")).split())
        lines += [
            "[[IgnoredVulns]]",
            f'id = "{vuln_id}"',
            f"ignoreUntil = {expires.isoformat()}",
            f'reason = "{reason}"',
            "",
        ]
        count += 1
    lines.append(f"# {count} ignored vulnerability entries rendered.")
    return "\n".join(lines) + "\n"


def main() -> int:
    if not EXCEPTIONS_PATH.exists():
        sys.stderr.write(f"gen-osv-config: missing {EXCEPTIONS_PATH}\n")
        return 1
    doc = yaml.safe_load(EXCEPTIONS_PATH.read_text(encoding="utf-8")) or {}
    OUTPUT_PATH.write_text(render(doc), encoding="utf-8")
    sys.stdout.write(f"gen-osv-config: wrote {OUTPUT_PATH.name}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
